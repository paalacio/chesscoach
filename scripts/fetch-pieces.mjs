#!/usr/bin/env node
// Downloads extra piece sets from the lichess (lila) repository into public/pieces/
// and writes src/styles/pieces.css. The output is committed, so this only needs
// to run again to add or update a set.
//
// Licenses (from lila's COPYING.md):
//   cburnett  Colin M.L. Burnett          GPLv2+     (bundled with chessground, not downloaded)
//   merida    Armando Hernandez Marroquin GPLv2+
//   chessnut  Alexis Luengas              Apache-2.0
// All are compatible with this app's GPL-3.0-or-later license.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const SETS = {
  merida: { author: "Armando Hernandez Marroquin", license: "GPL-2.0-or-later" },
  chessnut: { author: "Alexis Luengas", license: "Apache-2.0" },
};
const BASE = "https://raw.githubusercontent.com/lichess-org/lila/master/public/piece";
const ROLES = { K: "king", Q: "queen", R: "rook", B: "bishop", N: "knight", P: "pawn" };

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
let css = "/* Generated by scripts/fetch-pieces.mjs. Piece sets other than cburnett.\n" +
  "   Applied with a class on the board wrapper, e.g. <div class=\"pieces-merida\">. */\n";

for (const [name, info] of Object.entries(SETS)) {
  const dir = path.join(root, "public", "pieces", name);
  fs.mkdirSync(dir, { recursive: true });
  css += `\n/* ${name}: ${info.author}, ${info.license} */\n`;
  for (const color of ["w", "b"]) {
    for (const [letter, role] of Object.entries(ROLES)) {
      const file = `${color}${letter}.svg`;
      const res = await fetch(`${BASE}/${name}/${file}`);
      if (!res.ok) throw new Error(`${name}/${file}: HTTP ${res.status}`);
      const svg = await res.text();
      if (!svg.includes("<svg")) throw new Error(`${name}/${file} is not an SVG`);
      fs.writeFileSync(path.join(dir, file), svg);
      const colorName = color === "w" ? "white" : "black";
      css += `.pieces-${name} .cg-wrap piece.${role}.${colorName} { background-image: url("/pieces/${name}/${file}"); }\n`;
    }
  }
  fs.writeFileSync(
    path.join(dir, "LICENSE.txt"),
    `Piece set "${name}" by ${info.author}.\nLicense: ${info.license}.\nSource: https://github.com/lichess-org/lila/tree/master/public/piece/${name}\n`,
  );
  console.log(`Saved ${name}`);
}

fs.writeFileSync(path.join(root, "src", "styles", "pieces.css"), css);
console.log("Wrote src/styles/pieces.css");
